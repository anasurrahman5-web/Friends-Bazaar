-- Secure checkout: server-side price/cost calculation and atomic stock reduction.
create or replace function public.create_public_order(
  p_customer_name text, p_phone text, p_address text, p_trx_id text, p_items jsonb
) returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  v_order_id uuid;
  v_code text;
  v_total numeric(12,2) := 0;
  v_cost numeric(12,2) := 0;
  v_item jsonb;
  v_product public.products%rowtype;
  v_qty integer;
begin
  if length(trim(coalesce(p_customer_name,''))) < 2
    or length(trim(coalesce(p_phone,''))) < 8
    or length(trim(coalesce(p_address,''))) < 5
    or length(trim(coalesce(p_trx_id,''))) < 4
    or jsonb_typeof(p_items) <> 'array'
    or jsonb_array_length(p_items) = 0
    or jsonb_array_length(p_items) > 30 then
    raise exception 'ক্রেতার তথ্য বা কার্ট সঠিক নয়।';
  end if;

  v_code := 'FB-' || upper(substr(replace(gen_random_uuid()::text,'-',''),1,10));
  insert into public.orders(order_code,customer_name,phone,address,trx_id)
  values(v_code,trim(p_customer_name),trim(p_phone),trim(p_address),trim(p_trx_id))
  returning id into v_order_id;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_qty := (v_item->>'qty')::integer;
    if v_qty < 1 or v_qty > 100 then raise exception 'পরিমাণ সঠিক নয়।'; end if;

    select * into v_product from public.products
      where id=(v_item->>'product_id')::bigint for update;
    if not found then raise exception 'একটি পণ্য পাওয়া যায়নি।'; end if;
    if v_product.stock < v_qty then raise exception 'স্টকে পর্যাপ্ত পণ্য নেই: %',v_product.name; end if;

    update public.products set stock=stock-v_qty where id=v_product.id;
    insert into public.order_items(order_id,product_id,product_name,unit_price,unit_cost,qty,line_total,line_cost)
    values(v_order_id,v_product.id,v_product.name,v_product.price,v_product.cost,v_qty,
      v_product.price*v_qty,v_product.cost*v_qty);
    v_total := v_total + v_product.price*v_qty;
    v_cost := v_cost + v_product.cost*v_qty;
  end loop;

  update public.orders set total=v_total,cost=v_cost,profit=v_total-v_cost where id=v_order_id;
  return jsonb_build_object('order_code',v_code,'total',v_total);
end;
$$;

revoke all on function public.create_public_order(text,text,text,text,jsonb) from public;
grant execute on function public.create_public_order(text,text,text,text,jsonb) to anon, authenticated;

